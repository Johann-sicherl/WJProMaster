import opencascade from "replicad-opencascadejs";
import { setOC, getOC, makeBox, makeCylinder } from "replicad";
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const require = createRequire(import.meta.url);
setOC(await (opencascade as any)({ locateFile: () => require.resolve("replicad-opencascadejs/wasm") }));
const oc: any = getOC();
const nomear = (l: any, n: string) => oc.TDataStd_Name.Set(l, new oc.TCollection_ExtendedString(n, true));
const loc = (x: number, y: number, z: number, ang = 0) => { const t = new oc.gp_Trsf(); t.SetTranslation(new oc.gp_Vec(x, y, z)); if (ang) { const r = new oc.gp_Trsf(); r.SetRotation(new oc.gp_Ax1(new oc.gp_Pnt(0, 0, 0), new oc.gp_Dir(1, 0, 0)), ang * Math.PI / 180); t.Multiply(r); } return new oc.TopLoc_Location(t); };
const doc = new oc.TDocStd_Document(new oc.TCollection_ExtendedString("XmlOcaf", true));
oc.XCAFDoc_ShapeTool.SetAutoNaming(false);
const tool = oc.XCAFDoc_DocumentTool.ShapeTool(doc.Main());
const base = tool.AddShape(makeBox([0, 0, 0], [100, 10, 60]).wrapped, false, true); nomear(base, "Base");
const pino = tool.AddShape(makeCylinder(5, 30, [0, 0, 0], [0, 1, 0]).wrapped, false, true); nomear(pino, "Pino Ø10");
const sub = tool.NewShape(); nomear(sub, "Suporte");
tool.AddComponent(sub, base, loc(0, 0, 0));
tool.AddComponent(sub, pino, loc(50, 10, 30));
const raiz = tool.NewShape(); nomear(raiz, "Conjunto");
tool.AddComponent(raiz, base, loc(0, 0, 0));
tool.AddComponent(raiz, pino, loc(20, 10, 30));
tool.AddComponent(raiz, pino, loc(80, 10, 30, 90));
tool.AddComponent(raiz, sub, loc(0, 100, 0));
tool.UpdateAssemblies();
const ws = new oc.XSControl_WorkSession();
const w = new oc.STEPCAFControl_Writer(ws, false);
w.SetNameMode(true);
oc.Interface_Static.SetIVal("write.step.assembly", 1);
console.log("ok", w.Perform(doc, "/a.step", new oc.Message_ProgressRange()));
writeFileSync(process.argv[2], oc.FS.readFile("/a.step"));
